/////////////////////////////////////////////////////////////////////////
// 2D position
//
class Position
{
    constructor(x, y) 
    {
        this.x = x;
        this.y = y;
    }
}

/////////////////////////////////////////////////////////////////////////
// 2D size
//
class Size
{
    constructor(w, h) 
    {
        this.width = w;
        this.height = h;
    }
}